#!/usr/bin/env node
/**
 * build-context.mjs — regenerate fxc-context.generated.mjs
 *
 * Reads the FactoryXChange service catalogue from ../_data/entities.json
 * and bakes two exports into an ES module the Worker imports:
 *
 *   BASE_CATALOGUE  — every live service as one grounding line (label, partner
 *                     + contact, category/soft, pillar, short desc, FXC link).
 *                     Same shape as chat_server.py's build_catalogue().
 *   SERVICE_DETAIL  — id -> { label, partner, duration, service_lead, full }.
 *                     The rich per-service block the Worker injects when a
 *                     visitor has one or more services in focus on the map.
 *
 * Price is deliberately EXCLUDED from both exports — it must never reach the
 * model or the browser.
 *
 * Unlike the practice-map build-context.mjs (which fetches GitHub READMEs),
 * this reads a single local JSON file — no network, no gh token needed.
 *
 * Run:   node build-context.mjs        (from chat-worker/)
 * Then:  npx wrangler deploy           (bakes the refreshed data into the Worker)
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ENTITIES = join(__dirname, '..', '_data', 'entities.json');
const OUT = join(__dirname, 'fxc-context.generated.mjs');

const data = JSON.parse(readFileSync(ENTITIES, 'utf8'));

const catLabel = Object.fromEntries(data.categories.map((c) => [c.id, c.label]));
const pilLabel = Object.fromEntries(data.pillars.map((p) => [p.id, p.label]));
const partner = Object.fromEntries(data.partners.map((p) => [p.id, p]));

// One grounding line per service — mirrors chat_server.py build_catalogue().
function catalogueLine(s) {
  const p = partner[s.partner];
  const soft = s.soft ? ` / ${catLabel[s.soft]}` : '';
  return (
    `- ${s.label} | partner: ${p.label} (${p.contact}) | ` +
    `category: ${catLabel[s.category]}${soft} | pillar: ${pilLabel[s.pillar]} | ` +
    `${s.desc} | ${s.url}`
  );
}

const BASE_CATALOGUE = data.services.map(catalogueLine).join('\n');

// Rich focus detail per service — NO price. Mirrors chat_server.py
// build_focus_block() field set (label, partner, duration, service lead, full).
const SERVICE_DETAIL = {};
for (const s of data.services) {
  SERVICE_DETAIL[s.id] = {
    label: s.label,
    partner: partner[s.partner].label,
    duration: s.duration || '',
    service_lead: s.service_lead || '',
    full: s.full || '',
  };
}

const banner =
  '// AUTO-GENERATED by build-context.mjs — do not edit by hand.\n' +
  '// Regenerate: node build-context.mjs   (then: npx wrangler deploy)\n' +
  '// Source: ../_data/entities.json  —  price is deliberately excluded.\n';

const body =
  `${banner}\n` +
  `export const BASE_CATALOGUE = ${JSON.stringify(BASE_CATALOGUE)};\n\n` +
  `export const SERVICE_DETAIL = ${JSON.stringify(SERVICE_DETAIL, null, 2)};\n`;

writeFileSync(OUT, body);

const detailCount = Object.keys(SERVICE_DETAIL).length;
console.log(`Wrote ${OUT}`);
console.log(
  `Baked ${data.services.length} catalogue lines (${BASE_CATALOGUE.length} chars) ` +
    `and ${detailCount} SERVICE_DETAIL entries.`
);
